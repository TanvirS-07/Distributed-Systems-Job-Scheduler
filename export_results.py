#!/usr/bin/env python3
"""Export client vs baseline results to a Markdown file.

Usage:
    python3 export_results.py                  # writes RESULTS.md
    python3 export_results.py -o docs/RESULTS.md
"""
import json
from argparse import ArgumentParser
from statistics import mean
from typing import List

BASELINE = ["atl", "ff", "bf", "fc", "fafc"]
METRICS = ["Turnaround time", "Resource utilisation", "Total rental cost"]
HIGHER_IS_BETTER = {"Resource utilisation"}


def fmt(metric: str, value: float) -> str:
    return f"{value:.0f}" if metric == "Turnaround time" else f"{value:.2f}"


def metric_table(client: dict, ref: dict, metric: str) -> List[str]:
    """Markdown table for one metric. The best value in each row is bold."""
    configs = [c for c, v in client[metric].items() if isinstance(v, (int, float)) and c in ref[metric]]
    if not configs:
        return []

    pick = max if metric in HIGHER_IS_BETTER else min
    header = ["Config"] + [a.upper() for a in BASELINE] + ["Yours"]
    lines = [
        f"### {metric}",
        "",
        "| " + " | ".join(header) + " |",
        "|" + "|".join(["---"] + ["---:"] * (len(header) - 1)) + "|",
    ]

    def row(name: str, values: List[float]) -> str:
        best = pick(values)
        cells = [f"**{fmt(metric, v)}**" if v == best else fmt(metric, v) for v in values]
        return f"| {name} | " + " | ".join(cells) + " |"

    for c in configs:
        lines.append(row(c, [ref[metric][c][a] for a in BASELINE] + [client[metric][c]]))

    averages = [mean(ref[metric][c][a] for c in configs) for a in BASELINE]
    averages.append(mean(client[metric][c] for c in configs))
    lines.append(row("**Average**", averages))
    lines.append("")
    return lines


def build_markdown(client: dict, ref: dict) -> str:
    lines = [
        "# Results",
        "",
        "Generated by `export_results.py` from `results/test_results.json` and `results/ref_results.json`.",
        "Turnaround time and cost: lower is better. Utilisation: higher is better. Best value per row in bold.",
        "",
    ]
    for metric in METRICS:
        lines.extend(metric_table(client, ref, metric))
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = ArgumentParser(description="Export results to Markdown")
    parser.add_argument("-t", "--client_results", default="results/test_results.json")
    parser.add_argument("-r", "--reference_results", default="results/ref_results.json")
    parser.add_argument("-o", "--output", default="RESULTS.md")
    args = parser.parse_args()

    with open(args.client_results, encoding="utf-8") as f:
        client = json.load(f)
    with open(args.reference_results, encoding="utf-8") as f:
        ref = json.load(f)

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(build_markdown(client, ref))
    print("Wrote", args.output)


if __name__ == "__main__":
    main()
